def draw(name):
    rows, palette = SPRITES[name], PALETTES[name]
    assert len(rows) == 12 and all(len(row) == 12 for row in rows), name
    image = Image.new("RGBA", (12, 12), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, cell in enumerate(row):
            if cell != ".":
                image.putpixel((x, y), tuple(int(palette[cell][i:i + 2], 16) for i in (1, 3, 5)) + (255,))
    return image.resize((12 * SCALE, 12 * SCALE), Image.NEAREST)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for name in SPRITES:
        draw(name).save(OUT / f"genre-{name}.png", optimize=True)
        print(f"genre-{name}.png  {GENRES[name]}")
